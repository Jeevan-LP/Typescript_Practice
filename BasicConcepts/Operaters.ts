console.log("Arthmetic Operators in TypeScript");
let a:number = 10;
let b:number = 5;
console.log("a + b =", a + b); // Addition
console.log("a - b =", a - b); // Subtraction
console.log("a * b =", a * b); // Multiplication
console.log("a / b =", a / b); // Division
console.log("a % b =", a % b); // Modulus
console.log("a ** b =", a ** b); // Exponentiation  

console.log("Relational Operators in TypeScript");
let x:number = 20;
let y:number = 10;
console.log("x > y =", x > y); // Greater than
console.log("x < y =", x < y); // Less than
console.log("x >= y =", x >= y); // Greater than or equal to
console.log("x <= y =", x <= y); // Less than or equal to
console.log("x == y =", x == y); // Equal to
console.log("x != y =", x != y); // Not equal to   

console.log("Logical Operators in TypeScript");
let p:boolean = true;
let q:boolean = false;
console.log("p && q =", p && q); // Logical AND
console.log("p || q =", p || q); // Logical OR
console.log("!p =", !p); // Logical NOT

console.log("Assignment Operators in TypeScript");
let n:number = 20;
let m:number = 10;

//console.log("++n =", ++n); // Pre-increment
//console.log("m++ =", m++); // Post-increment
console.log("n-- =", n--); // Post-decrement
console.log("--m =", --m); // Pre-decrement
console.log("n += m =", n += m); // Addition assignment
console.log("n -= m =", n -= m); // Subtraction assignment
console.log("n *= m =", n *= m); // Multiplication assignment
console.log("n /= m =", n /= m); // Division assignment
console.log("n %= m =", n %= m); // Modulus assignment
console.log("n **= m =", n **= m); // Exponentiation assignment